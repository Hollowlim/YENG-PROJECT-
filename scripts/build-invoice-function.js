import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

// A single reviewable file can be pasted into the Supabase Dashboard editor.
// Only public source is bundled; secrets are still read from Deno.env at runtime.
const result = await build({
  entryPoints: ["supabase/functions/sample-checkout/index.ts"],
  bundle: true, format: "esm", platform: "neutral", target: "es2022",
  external: ["npm:*"], write: false,
});
const banner = "// Generated by npm run build:invoice-function. Edit checkout/invoice.js or supabase/functions/sample-checkout instead.\n";
await writeFile("supabase/sample-checkout.js", banner + result.outputFiles[0].text);
console.log("Built supabase/sample-checkout.js for the Supabase Edge Function editor.");
